export function getLevelGuide(level: CefrLevel): LevelGuide {
  const guide = LEVEL_GUIDES.find((item) => item.level === level);
  if (!guide) {
    throw new Error(`Нет описания для уровня ${level}.`);
  }
  return guide;
}
